// Generates the API reference (content/docs/api-reference) from docs/openapi.yaml.
//
// One page per operation: endpoint, authentication and scopes, every parameter, every
// request field (nested fields flattened), every response with its fields and an example,
// the operation's error codes with their meaning, and the same call in curl, TypeScript,
// Python, PHP and Go. Nothing is written by hand, so the reference cannot drift from the
// contract, and the contract itself is checked against the server's routes by the Go tests.
//
//   node scripts/generate-reference.mjs           write the pages
//   node scripts/generate-reference.mjs --check   fail if the committed pages are stale
//
// Every example (request and response) is validated against its schema here; an example
// that does not match the contract stops the build.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadSpec, resolve, validator } from "./lib/openapi.mjs";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const OUT = path.join(ROOT, "content", "docs", "api-reference");
const ERRORS_PAGE = path.join(ROOT, "content", "docs", "api", "rate-limits-and-errors.mdx");
const METHODS = ["get", "post", "put", "patch", "delete"];
const SAMPLE_ID = "6f1c2d0e-3b52-4d49-9a43-7d1f0c5e8a11";
// A YAML comment in the frontmatter: invisible on the page, obvious in the file.
const HEADER = "# Generated by scripts/generate-reference.mjs from docs/openapi.yaml. Do not edit: change the contract and regenerate.";

const spec = loadSpec();
const problems = [];

// ---------------------------------------------------------------- text helpers

/** Prose for MDX: no expressions, no elements, no table breaks. */
function prose(s = "") {
  // Inline code spans are kept verbatim: MDX renders them literally.
  return String(s)
    .replace(/\s+/g, " ")
    .trim()
    .split(/(`[^`]*`)/)
    .map((part, i) => (i % 2 ? part : escapeProse(part)))
    .join("");
}
function escapeProse(s) {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/\{/g, "&#123;")
    .replace(/\}/g, "&#125;");
}
/** Inline code that is safe in a table cell. */
const code = (s) => "`" + String(s).replace(/\|/g, "\\|").replace(/`/g, "'") + "`";
const cell = (s) => prose(s).replace(/\|/g, "\\|");
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/[^A-Za-z0-9]+/g, "-").toLowerCase().replace(/^-|-$/g, "");
const yamlStr = (s) => JSON.stringify(String(s));
/** Joins sentences without doubling the full stop. */
const sentences = (parts) => parts.filter(Boolean).map((p) => p.replace(/[.\s]+$/, "")).join(". ") + (parts.some(Boolean) ? "." : "");

// ---------------------------------------------------------------- schemas

/** Resolves $ref and merges allOf into one object schema (the contract uses allOf for pages). */
function deref(node) {
  if (node && node.$ref) return deref(node.$ref.replace(/^#\//, "").split("/").reduce((o, k) => o?.[k], spec));
  if (node && Array.isArray(node.allOf)) {
    const merged = { type: "object", properties: {}, required: [] };
    for (const part of node.allOf.map(deref)) {
      Object.assign(merged.properties, part.properties ?? {});
      merged.required.push(...(part.required ?? []));
      if (part.description && !merged.description) merged.description = part.description;
    }
    if (node.description) merged.description = node.description;
    return merged;
  }
  return node;
}

function typeOf(s) {
  s = deref(s) ?? {};
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (s.type === "array") return `array of ${typeOf(s.items)}`;
  if (s.type === "object" && s.additionalProperties && typeof s.additionalProperties === "object" && !s.properties)
    return `map of string to ${typeOf(s.additionalProperties)}`;
  return s.format ? `${s.type ?? "any"} (${s.format})` : s.type ?? "any";
}

function constraints(s) {
  s = deref(s) ?? {};
  const c = [];
  if (s.default !== undefined) c.push(`default ${code(JSON.stringify(s.default))}`);
  if (s.minimum !== undefined) c.push(`minimum ${s.minimum}`);
  if (s.maximum !== undefined) c.push(`maximum ${s.maximum}`);
  if (s.minLength !== undefined) c.push(`at least ${s.minLength} characters`);
  if (s.maxLength !== undefined) c.push(`at most ${s.maxLength} characters`);
  if (s.minItems !== undefined) c.push(`at least ${s.minItems} items`);
  if (s.maxItems !== undefined) c.push(`at most ${s.maxItems} items`);
  if (s.pattern) c.push(`pattern ${code(s.pattern)}`);
  if (s.type === "object" && s.additionalProperties === false) c.push("no other fields");
  if (s.nullable) c.push("may be null");
  return c;
}

/** Flattens an object schema into rows: name, type, required, description. */
function fieldRows(schema, prefix = "", depth = 0) {
  const s = deref(schema) ?? {};
  const rows = [];
  if (depth > 4) return rows;
  if (s.type === "array" && deref(s.items)?.properties) return fieldRows(s.items, prefix + "[]", depth + 1);
  const req = new Set(s.required ?? []);
  for (const [name, raw] of Object.entries(s.properties ?? {})) {
    const p = deref(raw) ?? {};
    const full = prefix ? `${prefix}.${name}` : name;
    const desc = sentences([p.description ? cell(p.description) : "", ...constraints(p)]);
    rows.push({ name: full, type: typeOf(p), required: req.has(name), desc });
    if (p.type === "object" && p.properties) rows.push(...fieldRows(p, full, depth + 1));
    if (p.type === "array" && deref(p.items)?.properties) rows.push(...fieldRows(p.items, full + "[]", depth + 1));
  }
  return rows;
}

function fieldTable(schema) {
  const rows = fieldRows(schema);
  if (!rows.length) {
    const s = deref(schema) ?? {};
    return `A ${code(typeOf(s))}${s.description ? `: ${prose(s.description)}` : "."}\n`;
  }
  return [
    "| Field | Type | Required | Description |",
    "|---|---|---|---|",
    ...rows.map((r) => `| ${code(r.name)} | ${cell(r.type)} | ${r.required ? "yes" : "no"} | ${r.desc || "&nbsp;"} |`),
  ].join("\n") + "\n";
}

/** An example built from a schema, used only when the contract gives none. */
function synth(schema, name = "", depth = 0) {
  const s = deref(schema) ?? {};
  if (s.example !== undefined) return s.example;
  if (s.default !== undefined) return s.default;
  if (s.enum) return s.enum[0];
  if (depth > 5) return null;
  switch (s.type) {
    case "object": {
      const out = {};
      const req = new Set(s.required ?? []);
      for (const [k, v] of Object.entries(s.properties ?? {})) {
        // Requests show the required fields; responses show every field.
        if (synth.requestOnly && !req.has(k)) continue;
        out[k] = synth(v, k, depth + 1);
      }
      return out;
    }
    case "array": {
      const one = synth(s.items, name, depth + 1);
      return one === undefined ? [] : [one];
    }
    case "integer":
    case "number":
      return s.minimum ?? 1;
    case "boolean":
      return false;
    case "string":
      if (s.format === "uuid" || /(^|_)id$/.test(name)) return SAMPLE_ID;
      if (s.format === "date-time" || /_at$/.test(name)) return "2026-11-17T10:00:00Z";
      if (s.format === "uri" || /url$/.test(name)) return "https://app.example.com/path";
      if (/email|^to$|^from$|address|recipient/.test(name)) return name === "from" ? "noreply@notify.example.com" : "user@example.org";
      return "string";
    default:
      return null;
  }
}
function requestExample(schema) {
  synth.requestOnly = true;
  try {
    return synth(schema);
  } finally {
    synth.requestOnly = false;
  }
}

function firstExample(media) {
  if (!media) return undefined;
  if (media.example !== undefined) return media.example;
  const ex = Object.values(media.examples ?? {})[0];
  return ex?.value;
}

function checkExample(where, schema, value) {
  if (value === undefined || schema === undefined) return;
  try {
    const validate = validator(spec, schema);
    if (!validate(value)) problems.push(`${where}: example does not match the schema: ${validate.errors.map((e) => `${e.instancePath} ${e.message}`).join("; ")}`);
  } catch (e) {
    problems.push(`${where}: schema could not be compiled: ${e.message}`);
  }
}

// ---------------------------------------------------------------- error codes

/** code -> [http, meaning] from the errors page, so meanings are written once. */
function errorMeanings() {
  const out = new Map();
  for (const line of fs.readFileSync(ERRORS_PAGE, "utf8").split("\n")) {
    const m = line.match(/^\|\s*`([a-z_]+)`\s*\|\s*([^|]+?)\s*\|\s*(.+?)\s*\|\s*$/);
    if (m) out.set(m[1], [m[2], m[3]]);
  }
  return out;
}
const MEANINGS = errorMeanings();

// ---------------------------------------------------------------- operations

function operations() {
  const ops = [];
  for (const [p, item] of Object.entries(spec.paths)) {
    for (const m of METHODS) {
      if (!item[m]) continue;
      const op = item[m];
      const params = [...(item.parameters ?? []), ...(op.parameters ?? [])].map(deref);
      ops.push({ method: m.toUpperCase(), path: p, op, params, tag: op.tags?.[0] ?? "Other" });
    }
  }
  return ops;
}

function auth(o) {
  const security = o.op.security ?? spec.security;
  if (Array.isArray(security) && security.length === 0) return { kind: "none" };
  const scopes = o.op["x-required-scopes"];
  const schemes = (security ?? [{ bearer: [] }]).flatMap((s) => Object.keys(s));
  return { kind: schemes.includes("bearer") ? "bearer" : "other", schemes, scopes };
}

/** Path with example values, as a shell expression and as a literal. */
function concretePath(o) {
  let shell = o.path;
  let literal = o.path;
  for (const p of o.params.filter((x) => x.in === "path")) {
    const v = deref(p.schema)?.format === "uuid" || /id$/.test(p.name) ? SAMPLE_ID : p.example ?? deref(p.schema)?.example ?? (p.name === "env" ? "sandbox" : `your-${p.name}`);
    shell = shell.replace(`{${p.name}}`, String(v));
    literal = literal.replace(`{${p.name}}`, String(v));
  }
  const q = o.params.filter((x) => x.in === "query" && x.required);
  if (q.length) {
    const qs = q.map((p) => `${p.name}=${encodeURIComponent(String(p.example ?? deref(p.schema)?.example ?? synth(p.schema, p.name)))}`).join("&");
    shell += "?" + qs;
    literal += "?" + qs;
  }
  return { shell, literal };
}

function samples(o, body, mediaType) {
  const a = auth(o);
  const idem = o.params.some((p) => p.in === "header" && p.name === "Idempotency-Key");
  const { literal } = concretePath(o);
  const json = body !== undefined && mediaType === "application/json";
  const pretty = json ? JSON.stringify(body, null, 2) : "";

  // curl
  const curl = [`curl -sS${o.method === "GET" ? "" : ` -X ${o.method}`} "$NJIWA_MAIL_URL${literal}"`];
  if (a.kind === "bearer") curl.push(`  -H "Authorization: Bearer $NJIWA_MAIL_API_KEY"`);
  if (idem) curl.push(`  -H "Idempotency-Key: $(uuidgen)"`);
  if (json) curl.push(`  -H "Content-Type: application/json"`, `  -d @- <<'JSON'\n${pretty}\nJSON`);
  else if (body !== undefined && mediaType === "application/x-www-form-urlencoded")
    curl.push(...Object.entries(body ?? {}).map(([k, v]) => `  --data-urlencode ${JSON.stringify(`${k}=${v}`)}`));
  else if (mediaType) curl.push(`  -H "Content-Type: ${mediaType}"`, `  --data-binary @message.eml`);
  const curlText = curl.map((l, i) => (i < curl.length - 1 && !l.includes("<<'JSON'") ? l + " \\" : l)).join("\n");

  if (mediaType && !json) return { curl: curlText }; // non-JSON bodies: curl only, honestly

  const hdrTs = [a.kind === "bearer" && `Authorization: \`Bearer \${process.env.NJIWA_MAIL_API_KEY}\``, idem && `"Idempotency-Key": randomUUID()`, json && `"Content-Type": "application/json"`].filter(Boolean);
  const ts = [
    ...(idem ? [`import { randomUUID } from "node:crypto";`, ""] : []),
    `const res = await fetch(\`\${process.env.NJIWA_MAIL_URL}${literal}\`, {`,
    `  method: "${o.method}",`,
    ...(hdrTs.length ? [`  headers: {`, ...hdrTs.map((h) => `    ${h},`), `  },`] : []),
    ...(json ? [`  body: JSON.stringify(${pretty.replace(/\n/g, "\n  ")}),`] : []),
    `});`,
    `if (!res.ok) throw new Error(\`Njiwa-Mail \${res.status}: \${await res.text()}\`);`,
    `console.log(await res.${o.path.endsWith("widget.js") ? "text" : "json"}());`,
  ].join("\n");

  const hdrPy = [a.kind === "bearer" && `"Authorization": "Bearer " + os.environ["NJIWA_MAIL_API_KEY"]`, idem && `"Idempotency-Key": str(uuid.uuid4())`].filter(Boolean);
  const pyBody = json ? JSON.stringify(body, null, 4).replace(/\btrue\b/g, "True").replace(/\bfalse\b/g, "False").replace(/\bnull\b/g, "None") : "";
  const py = [
    "import os",
    ...(idem ? ["import uuid"] : []),
    "",
    "import requests",
    "",
    `response = requests.${o.method.toLowerCase()}(`,
    `    os.environ["NJIWA_MAIL_URL"] + ${JSON.stringify(literal)},`,
    ...(hdrPy.length ? [`    headers={`, ...hdrPy.map((h) => `        ${h},`), `    },`] : []),
    ...(json ? [`    json=${pyBody.replace(/\n/g, "\n    ")},`] : []),
    `    timeout=10,`,
    `)`,
    `response.raise_for_status()`,
    `print(response.${o.path.endsWith("widget.js") ? "text" : "json()"})`,
  ].join("\n");

  const phpArr = (v, ind) => {
    if (Array.isArray(v)) return "[" + v.map((x) => phpArr(x, ind)).join(", ") + "]";
    if (v && typeof v === "object")
      return "[\n" + Object.entries(v).map(([k, x]) => `${" ".repeat(ind + 4)}${JSON.stringify(k).replace(/^"|"$/g, "'")} => ${phpArr(x, ind + 4)},`).join("\n") + `\n${" ".repeat(ind)}]`;
    if (typeof v === "string") return "'" + v.replace(/\\/g, "\\\\").replace(/'/g, "\\'") + "'";
    return v === null ? "null" : String(v);
  };
  const php = [
    "<?php",
    "",
    "use Illuminate\\Support\\Facades\\Http;",
    ...(idem ? ["use Illuminate\\Support\\Str;"] : []),
    "",
    `$response = Http::${a.kind === "bearer" ? "withToken(config('services.njiwa.key'))\n    ->" : ""}${idem ? "withHeaders(['Idempotency-Key' => (string) Str::uuid()])\n    ->" : ""}timeout(10)`,
    `    ->${o.method.toLowerCase()}(rtrim(config('services.njiwa.url'), '/') . '${literal}'${json ? ", " + phpArr(body, 4) : ""})`,
    `    ->throw();`,
    "",
    `$data = $response->${o.path.endsWith("widget.js") ? "body" : "json"}();`,
  ].join("\n");

  const go = [
    "package main",
    "",
    "import (",
    ...[...(json ? ["bytes"] : []), ...(idem ? ["crypto/rand", "encoding/hex"] : []), "fmt", "io", "log", "net/http", "os"].sort().map((p) => `\t"${p}"`),
    ")",
    "",
    "func main() {",
    ...(json ? ["\tbody := []byte(`" + JSON.stringify(body) + "`)"] : []),
    `\treq, err := http.NewRequest("${o.method}", os.Getenv("NJIWA_MAIL_URL")+"${literal}", ${json ? "bytes.NewReader(body)" : "nil"})`,
    "\tif err != nil {",
    "\t\tlog.Fatal(err)",
    "\t}",
    ...(a.kind === "bearer" ? ['\treq.Header.Set("Authorization", "Bearer "+os.Getenv("NJIWA_MAIL_API_KEY"))'] : []),
    ...(idem ? ["\tb := make([]byte, 16)", "\t_, _ = rand.Read(b)", '\treq.Header.Set("Idempotency-Key", "req:"+hex.EncodeToString(b)) // reuse it when you retry'] : []),
    ...(json ? ['\treq.Header.Set("Content-Type", "application/json")'] : []),
    "\tres, err := http.DefaultClient.Do(req)",
    "\tif err != nil {",
    "\t\tlog.Fatal(err)",
    "\t}",
    "\tdefer res.Body.Close()",
    "\tout, _ := io.ReadAll(res.Body)",
    "\tfmt.Println(res.StatusCode, string(out))",
    "}",
  ].join("\n");

  return { curl: curlText, ts, py, php, go };
}

// ---------------------------------------------------------------- pages

function page(o) {
  const { op } = o;
  const a = auth(o);
  const where = `${o.method} ${o.path}`;
  const lines = [];
  const title = op.summary ?? where;
  lines.push("---", HEADER, `title: ${yamlStr(title)}`, `description: ${yamlStr(op.summary ? `${op.summary} (${where})` : where)}`, "---", "");
  lines.push("```http", `${o.method} ${o.path}`, "```", "");
  if (op.description) lines.push(prose(op.description), "");

  // Authentication
  lines.push("## Authentication", "");
  if (a.kind === "none") lines.push("None. This endpoint is public: it is called by browsers or mail clients, never with your API key.", "");
  else if (a.kind === "bearer") {
    lines.push("Send a server-side API key: `Authorization: Bearer $NJIWA_MAIL_API_KEY`. See [Authentication](/docs/authentication).", "");
    if (a.scopes?.length) lines.push(`Required scope: ${a.scopes.map((s) => s.split(/\s+or\s+/).map(code).join(" or ")).join(", ")}.`, "");
  } else lines.push(`Uses ${a.schemes.map(code).join(", ")} as described below, not an API key.`, "");
  for (const name of a.schemes ?? []) {
    const sch = spec.components?.securitySchemes?.[name];
    if (sch && name !== "bearer" && sch.description) lines.push(`${code(name)}: ${prose(sch.description)}`, "");
  }

  // Parameters
  const params = o.params.filter((p) => p.in !== "cookie");
  if (params.length) {
    lines.push("## Parameters", "", "| Name | In | Type | Required | Description |", "|---|---|---|---|---|");
    for (const p of params) {
      const desc = sentences([p.description ? cell(p.description) : "", ...constraints(p.schema)]);
      lines.push(`| ${code(p.name)} | ${p.in} | ${cell(typeOf(p.schema))} | ${p.required ? "yes" : "no"} | ${desc || "&nbsp;"} |`);
    }
    lines.push("");
  }

  // Request body
  let body;
  let mediaType;
  if (op.requestBody) {
    const rb = deref(op.requestBody);
    const [mt, media] = Object.entries(rb.content ?? {})[0] ?? [];
    mediaType = mt;
    lines.push("## Request body", "", `Content type: ${code(mt)}.${rb.required ? " Required." : ""}${rb.description ? " " + prose(rb.description) : ""}`, "");
    if (media?.schema) {
      const s = deref(media.schema);
      if (s.description) lines.push(prose(s.description), "");
      lines.push(fieldTable(media.schema));
      body = firstExample(media);
      if (body === undefined && mt === "application/json") body = requestExample(media.schema);
      if (mt === "application/json") checkExample(`${where} request`, media.schema, body);
      if (body !== undefined && mt === "application/json") lines.push("Example:", "", "```json", JSON.stringify(body, null, 2), "```", "");
      // Further named examples from the contract.
      for (const [name, ex] of Object.entries(media.examples ?? {}).slice(1)) {
        checkExample(`${where} example ${name}`, media.schema, ex.value);
        lines.push(`Example: ${prose(ex.summary ?? name)}`, "", "```json", JSON.stringify(ex.value, null, 2), "```", "");
      }
    }
  }

  // Code samples
  const s = samples(o, body, mediaType);
  lines.push("## Code examples", "");
  if (s.ts) {
    lines.push('<Tabs items={["curl", "TypeScript", "Python", "PHP", "Go"]}>');
    for (const [label, lang, text] of [["curl", "bash", s.curl], ["TypeScript", "ts", s.ts], ["Python", "python check", s.py], ["PHP", "php check", s.php], ["Go", "go", s.go]])
      lines.push(`<Tab value="${label}">`, "", "```" + lang, text, "```", "", "</Tab>");
    lines.push("</Tabs>", "");
  } else lines.push("```bash", s.curl, "```", "");
  if (a.kind === "bearer") lines.push("Keys belong on your server: never put them in a browser, a mobile app, a URL or a log.", "");

  // Responses
  lines.push("## Responses", "");
  for (const [status, raw] of Object.entries(op.responses ?? {})) {
    const r = deref(raw);
    lines.push(`### ${status}`, "", prose(r.description ?? ""), "");
    for (const [hname, h] of Object.entries(r.headers ?? {})) lines.push(`Header ${code(hname)}: ${prose(deref(h).description ?? typeOf(deref(h).schema))}`, "");
    const [mt, media] = Object.entries(r.content ?? {})[0] ?? [];
    if (!media) continue;
    if (mt !== "application/json") {
      lines.push(`Content type: ${code(mt)}.`, "");
      continue;
    }
    const schema = media.schema;
    const isError = deref(schema) === deref({ $ref: "#/components/schemas/Error" });
    if (!isError) lines.push(fieldTable(schema));
    let ex = firstExample(media);
    if (ex === undefined && isError) {
      // A real code this operation returns with this status, not a placeholder.
      const real = (op["x-error-codes"] ?? []).find((c) => MEANINGS.get(c)?.[0].trim() === status);
      const named = (r.description ?? "").match(/^([a-z]+(?:_[a-z]+)+)/)?.[1];
      ex = { error: { code: real ?? named ?? (status === "404" ? "not_found" : "invalid_request") } };
    }
    if (ex === undefined) ex = synth(schema);
    checkExample(`${where} ${status}`, schema, ex);
    lines.push("```json", JSON.stringify(ex, null, 2), "```", "");
  }

  // Errors
  const codes = op["x-error-codes"] ?? [];
  if (codes.length) {
    lines.push("## Error codes", "", "Errors share one shape: `error.code` is stable, `error.message` is optional detail. Retry only timeouts, network errors, `429` and `5xx`, with the same idempotency key; fix the request for every other `4xx`.", "");
    lines.push("| Code | HTTP | Meaning |", "|---|---|---|");
    for (const c of codes) {
      const m = MEANINGS.get(c);
      if (!m) problems.push(`${where}: error code ${c} has no meaning on the errors page`);
      lines.push(`| ${code(c)} | ${m ? cell(m[0]) : "&nbsp;"} | ${m ? m[1] : "&nbsp;"} |`);
    }
    lines.push("", "Every code is explained on [Rate limits and errors](/docs/api/rate-limits-and-errors).", "");
  }
  return lines.join("\n").replace(/\n{3,}/g, "\n\n");
}

